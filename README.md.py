#Este proyecto del Sprint #9, nos ayuda a escribir varias pruebas para comprobar que la página de Urban Routes funcione como debe funcionar,
# En este proyecto se busca definir localizadores, métodos necesarios y algunas pruebas auntomatizadas que cubran todos los pasos o el proceso para pedir un taxi

#Este proyecto se utilizaron estas herramientas:
#Pytest 9.0.2
#Python 3.14
#PyCharm 2025.3.2.1
#Selenium 4.41.0

#Este archivo contiene las siguientes pestañas:
#helpers.py - contiene funciones auxiliares que ya vienen preparadas en el repositorio para ayudarte con tareas específicas del proyecto.
#README.md.py - contiene una explicación de como funciona este proyecto y lo que contiene
#data.py - contiene todos los datos necesarios para poder ejecutar adecuadamente las pruebas
#page.py - contiene los métodos necesarios para cada funcionalidad que se desarrollan en la pestaña de "test_main.py"
#test_main.py - contiene los métodos de prueba, uno para cada funcionalidad

#Instrucciones:
#El código se debe ejecutar actualizando la URL del sitio "URBAN ROUTES", una vez haciendo esto, se debe dar clic en el botón play que se encuentra en la pate superior derecha de esta misma página.

#El proyecto consiste en ejecutar 9 pruebas:
#La primera prueba es: Configurar la dirección (esta parte se ha escrito para ti como ejemplo).
#La segunda prueba es: Seleccionar la tarifa Comfort.
#La tercera prueba es: Rellenar el número de teléfono.
#La cuarta prueba es: Agregar una tarjeta de crédito.
#La quinta prueba es: Escribir un mensaje para el controlador.
#La sexta prueba es: Pedir una manta y pañuelos.
#La septima prueba es: Pedir 2 helados.
#La octava prueba es: Aparece el modal para buscar un taxi.
#La novena prueba es: Esperar a que aparezca la información del conductor en el modal (opcional).